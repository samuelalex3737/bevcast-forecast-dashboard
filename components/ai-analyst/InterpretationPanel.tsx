"use client";

import type { ReactNode } from "react";
import { AlertTriangle, Bot, CheckCircle2, Cpu, Gauge, ListChecks, Loader2, RefreshCw, ShieldAlert, Sparkles, Target, TrendingUp } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Switch } from "@/components/ui/switch";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { useAppStore } from "@/lib/store/useAppStore";
import { useInterpretationView } from "@/lib/store/useAiAnalyst";
import { GroundedText, GroundingBadge } from "./GroundingBadge";
import { PanelErrorBoundary } from "@/components/shared/PanelErrorBoundary";
import type { Interpretation } from "@/lib/llm/schema";
import { cn } from "@/lib/utils";

function Section({ icon, title, children, className }: { icon: ReactNode; title: string; children: ReactNode; className?: string }) {
  return (
    <section className={cn("flex flex-col gap-2 rounded-xl border bg-card p-4 shadow-sm", className)}>
      <h3 className="flex items-center gap-2 text-[13px] font-semibold tracking-wide text-muted-foreground uppercase">
        {icon}
        {title}
      </h3>
      <div className="text-[13.5px] leading-relaxed">{children}</div>
    </section>
  );
}

const PRIORITY = { high: "bg-danger-soft text-danger", medium: "bg-warning-soft text-warning", low: "bg-success-soft text-success" } as const;
const VERDICT = { captured: "bg-success-soft text-success", "partially captured": "bg-warning-soft text-warning", "not captured": "bg-danger-soft text-danger" } as const;

export function StatusBar() {
  const provider = useAppStore((s) => s.provider);
  const autoUpdate = useAppStore((s) => s.autoUpdateAI);
  const setAuto = useAppStore((s) => s.setAutoUpdateAI);
  const regenerate = useAppStore((s) => s.requestRegenerate);
  const { response, loading } = useInterpretationView();
  return (
    <div className="flex flex-wrap items-center justify-between gap-3 rounded-xl border bg-card p-3 shadow-sm">
      <div className="flex min-w-0 flex-wrap items-center gap-2">
        {provider?.configured ? (
          <Badge className="h-auto max-w-full bg-success-soft py-1 whitespace-normal text-success" variant="secondary">
            <Cpu className="size-3" aria-hidden />
            LLM connected - {provider.provider}/{provider.model}
          </Badge>
        ) : (
          <Badge variant="secondary" className="h-auto max-w-full bg-warning-soft py-1 whitespace-normal text-warning">
            <Cpu className="size-3" aria-hidden />
            {provider ? "LLM not configured - showing rule-based analysis" : "Checking LLM connection..."}
          </Badge>
        )}
        {response ? (
          <Badge variant="outline" className="h-auto max-w-full py-1 whitespace-normal">
            {response.source === "llm" ? <Sparkles className="size-3" aria-hidden /> : <Bot className="size-3" aria-hidden />}
            {response.source === "llm" ? `Generated by ${response.model} in ${(response.latency_ms / 1000).toFixed(1)} s` : "Deterministic rule-based engine"}
          </Badge>
        ) : null}
        {response?.fallback_reason ? <span className="text-[12px] text-muted-foreground">{response.fallback_reason}</span> : null}
        {response?.completed_fields?.length ? (
          <span className="text-[12px] text-muted-foreground">The LLM omitted {response.completed_fields.map((f) => f.replace(/_/g, " ")).join(", ")}; those sections come from the rule-based engine.</span>
        ) : null}
      </div>
      <div className="flex items-center gap-3">
        <label className="flex items-center gap-2 text-[13px]">
          <Switch checked={autoUpdate} onCheckedChange={(v) => setAuto(Boolean(v))} aria-label="Auto-update interpretation when data changes" />
          Auto-update
        </label>
        <Button size="sm" onClick={regenerate} disabled={loading}>
          {loading ? <Loader2 className="size-3.5 animate-spin" aria-hidden /> : <RefreshCw className="size-3.5" aria-hidden />}
          Regenerate
        </Button>
      </div>
    </div>
  );
}

export function InterpretationPanel() {
  const { snapshot, response, stale, loading } = useInterpretationView();
  const regenerate = useAppStore((s) => s.requestRegenerate);
  const interp: Interpretation | undefined = response?.interpretation;

  if (!snapshot) {
    return <p className="text-sm text-muted-foreground">The analysis appears once at least 4 months of data are loaded and the models have been trained.</p>;
  }
  if (!interp) {
    return (
      <div className="flex min-h-48 items-center justify-center gap-2 rounded-xl border border-dashed text-sm text-muted-foreground">
        <Loader2 className="size-4 animate-spin" aria-hidden />
        Interpreting the live results (snapshot {snapshot.snapshot_id})...
      </div>
    );
  }
  const G = ({ text }: { text: string }) => <GroundedText text={text} payload={snapshot} />;

  return (
    <PanelErrorBoundary name="AI interpretation">
      <div className="space-y-4">
        {stale ? (
          <Alert className="border-warning/50 bg-warning-soft">
            <AlertTriangle className="size-4 text-warning" aria-hidden />
            <AlertTitle>Stale - data changed</AlertTitle>
            <AlertDescription className="flex flex-wrap items-center justify-between gap-2">
              <span>This interpretation was written for snapshot {response?.snapshot_id}; the live data is now {snapshot.snapshot_id}. Figures that no longer match are underlined.</span>
              <Button size="sm" variant="outline" onClick={regenerate} disabled={loading}>
                {loading ? <Loader2 className="size-3.5 animate-spin" aria-hidden /> : <RefreshCw className="size-3.5" aria-hidden />}
                Regenerate
              </Button>
            </AlertDescription>
          </Alert>
        ) : null}

        <div className="flex flex-wrap items-center gap-2">
          <GroundingBadge interpretation={interp} payload={snapshot} />
          <span className="text-[12px] text-muted-foreground">Snapshot {response?.snapshot_id}</span>
        </div>

        <Section icon={<Sparkles className="size-4 text-brand" aria-hidden />} title="Executive summary" className="border-brand/30 bg-brand-soft/40">
          <p className="text-[15px]">
            <G text={interp.executive_summary} />
          </p>
        </Section>

        <div className="grid gap-4 lg:grid-cols-2">
          <Section icon={<TrendingUp className="size-4" aria-hidden />} title="Q1. Seasonality and trend">
            <span className={cn("mb-2 inline-flex w-fit rounded-full px-2.5 py-0.5 text-xs font-semibold capitalize", VERDICT[interp.seasonality_and_trend.verdict])}>{interp.seasonality_and_trend.verdict}</span>
            <p>
              <G text={interp.seasonality_and_trend.explanation} />
            </p>
          </Section>
          <Section icon={<Target className="size-4" aria-hidden />} title="Q2. Best model and why">
            <p className="font-semibold">{interp.best_model.name}</p>
            <p className="mt-1">
              <G text={interp.best_model.why} />
            </p>
            <p className="mt-2 text-[12.5px] text-muted-foreground">
              <span className="font-medium text-foreground">Caveats: </span>
              <G text={interp.best_model.caveats} />
            </p>
          </Section>
        </div>

        <Section icon={<Gauge className="size-4" aria-hidden />} title="Model comparison">
          <G text={interp.model_comparison_insight} />
        </Section>

        <Section icon={<ListChecks className="size-4" aria-hidden />} title="Q3. Recommendations">
          <ol className="space-y-3">
            {interp.recommendations.map((r, i) => (
              <li key={i} className="flex gap-3 rounded-lg border p-3">
                <span className="flex size-6 shrink-0 items-center justify-center rounded-full bg-brand text-xs font-semibold text-brand-foreground">{i + 1}</span>
                <div className="min-w-0 flex-1 space-y-1">
                  <div className="flex flex-wrap items-center gap-1.5">
                    <span className={cn("rounded-full px-2 py-0.5 text-[11px] font-semibold capitalize", PRIORITY[r.priority])}>{r.priority}</span>
                    <Badge variant="outline" className="text-[11px]">{r.owner}</Badge>
                  </div>
                  <p className="font-medium">
                    <G text={r.action} />
                  </p>
                  <p className="text-[12.5px] text-muted-foreground">
                    <G text={r.rationale} />
                  </p>
                  <p className="flex w-fit max-w-full items-start gap-1 rounded bg-muted px-1.5 py-0.5 text-[11.5px] break-words">
                    <CheckCircle2 className="mt-0.5 size-3 shrink-0 text-success" aria-hidden />
                    <span>
                      <G text={r.metric_cited} />
                    </span>
                  </p>
                </div>
              </li>
            ))}
          </ol>
        </Section>

        <div className="grid gap-4 lg:grid-cols-3">
          <Section icon={<ShieldAlert className="size-4" aria-hidden />} title="Risks">
            <ul className="list-disc space-y-1.5 pl-4">
              {interp.risks.map((r, i) => (
                <li key={i}>
                  <G text={r} />
                </li>
              ))}
            </ul>
          </Section>
          <Section icon={<AlertTriangle className="size-4" aria-hidden />} title="Data limitations">
            <ul className="list-disc space-y-1.5 pl-4">
              {interp.data_limitations.map((r, i) => (
                <li key={i}>
                  <G text={r} />
                </li>
              ))}
            </ul>
          </Section>
          <Section icon={<ListChecks className="size-4" aria-hidden />} title="Next steps">
            <ul className="list-disc space-y-1.5 pl-4">
              {interp.next_steps.map((r, i) => (
                <li key={i}>
                  <G text={r} />
                </li>
              ))}
            </ul>
          </Section>
        </div>
      </div>
    </PanelErrorBoundary>
  );
}
